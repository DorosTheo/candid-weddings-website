/**
 * Writes public/__forms.html — the hidden static copy of the inquiry form that
 * Netlify Forms needs for detection. Runs automatically before `npm run build`.
 */
import { writeFileSync } from "node:fs";
import path from "node:path";
import {
  NETLIFY_FORM_NAME,
  NETLIFY_HONEYPOT,
  NETLIFY_SUBJECT,
  netlifyFieldNames,
} from "../src/lib/netlify-form.ts";

const esc = (s: string) => s.replace(/&/g, "&amp;").replace(/"/g, "&quot;").replace(/</g, "&lt;");
const fields = Object.entries(netlifyFieldNames)
  .map(([key, name]) =>
    key === "message"
      ? `    <textarea name="${esc(name)}"></textarea>`
      : `    <input type="${key === "email" ? "email" : "text"}" name="${esc(name)}" />`,
  )
  .join("\n");

const html = `<!doctype html>
<!-- GENERATED by scripts/generate-forms-html.ts — do not edit by hand. -->
<!-- Hidden form definition so Netlify Forms can detect the inquiry form. -->
<html lang="en">
  <head><meta charset="utf-8" /><meta name="robots" content="noindex" /><title>Forms</title></head>
  <body>
  <form name="${NETLIFY_FORM_NAME}" data-netlify="true" netlify-honeypot="${NETLIFY_HONEYPOT}" hidden>
    <input type="hidden" name="form-name" value="${NETLIFY_FORM_NAME}" />
    <input type="hidden" name="subject" value="${esc(NETLIFY_SUBJECT)}" />
${fields}
    <input type="text" name="${NETLIFY_HONEYPOT}" />
  </form>
  </body>
</html>
`;
writeFileSync(path.resolve(import.meta.dirname, "../public/__forms.html"), html);
console.log("Wrote public/__forms.html");
